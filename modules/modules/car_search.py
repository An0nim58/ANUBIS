class CarScanner:
    def __init__(self, plate: str):
        self.plate = plate.strip().upper().replace(" ", "")

    def validate_and_parse(self) -> tuple:
        """Проверяет формат номера РФ (например, А777АА77 или А777АА177)"""
        # Регулярное выражение для стандартных номеров РФ типу А123БВ45(6)
        pattern = r"^([ABEKMHOPCTYX])(\d{3})([ABEKMHOPCTYX]{2})(\d{2,3})$"
        match = re.match(pattern, self.plate)
        if match:
            return True, match.group(1), match.group(2), match.group(3), match.group(4)
        return False, None, None, None, None

    async def scan(self) -> dict:
        """Главный метод анализа госномера"""
        is_valid, letter1, digits, letters2, region_code = self.validate_and_parse()

        results = {
            "valid": is_valid,
            "formatted": f"{letter1}{digits}{letters2} {region_code}" if is_valid else self.plate,
            "region_name": "Неизвестный регион",
            "links": []
        }

        if is_valid:
            # Ищем регион в нашем словаре
            results["region_name"] = REGIONS_RF.get(region_code, f"Код {region_code} (Новый или редкий регион)")

            # Переводим в нижний регистр для формирования URL
            raw_plate = self.plate.lower()

            # Генерируем OSINT-ссылки для глубокого поиска
            results["links"] = [
                f"https://google.com{self.plate}%22 (Поиск упоминаний госномера в Google)",
                f"https://nomerogram.ru{raw_plate}/ (Проверка фото машины и истории на Номерограм)",
                f"https://autoteka.ru (Для ручной проверки истории через Автотеку)",
                f"https://gibdd.ru (Официальная проверка истории ГИБДД)"
            ]

        return results
